# 4. 레이아웃 배치를 위한 컬럼 분할 (왼쪽: 지도, 오른쪽: 상세 정보 카드)
col1, col2 = st.columns([1.5, 1])

with col1:
    st.subheader("🗺️ 서울 핫플 지도 (마우스를 올려보세요!)")
    
    # 서울 중심부 좌표로 기본 지도 생성 (Zoom: 12)
    m = folium.Map(location=[37.5560, 126.9723], zoom_start=12, control_scale=True)
    
    # 10개 장소 마커 찍기 (요구사항: 하늘색 마커 + 호버 시 지하철역 노출)
    for spot in seoul_hotspots:
        folium.Marker(
            location=[spot["lat"], spot["lng"]],
            popup=folium.Popup(f"<b>{spot['name']}</b><br>{spot['subway']}", max_width=300),
            tooltip=f"📍 {spot['name']} ({spot['subway']})",  # 마우스 호버(올렸을 때) 툴팁 작동
            icon=folium.Icon(color="cadetblue", icon="info-sign")  # 요구사항: 하늘색(cadetblue) 마커 반영
        ).add_to(m)
    
    # 스트림릿 웹 앱에 지도를 꽉 차게 렌더링
    st_folium(m, width="100%", height=600)

with col2:
    st.subheader("✨ 장소별 꿀잼 상세 정보")
    
    # 유저가 골라서 볼 수 있도록 셀렉트박스 제공
    selected_spot_name = st.selectbox(
        "자세히 알아보고 싶은 핫플을 선택해봐!",
        [spot["name"] for spot in seoul_hotspots]
    )
    
    # 선택된 장소의 데이터를 찾아 화면에 예쁘게 카드 형태로 출력
    for spot in seoul_hotspots:
        if spot["name"] == selected_spot_name:
            st.info(f"🚇 **가장 가까운 역:** {spot['subway']}")
            st.success(f"💡 **여기서 뭐하고 놀까?**\n\n{spot['fun']}")
